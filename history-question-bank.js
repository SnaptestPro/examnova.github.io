  async function seedHistoryQuestionBank() {
    const db = window.vishnuFirebase?.enabled ? window.vishnuFirebase.db : null;
    if (!db) return;

    // Pehle se delete kiye gaye questions dobara seed na hon, isliye unki ID list nikal lo.
    let deletedIds = new Set();
    try {
      const [delSnap, exclSnap] = await Promise.all([
        db.collection("deletedQuestions").get(),
        db.collection("seedExclusions").get()
      ]);
      delSnap.docs.forEach(d => deletedIds.add(d.id));
      exclSnap.docs.forEach(d => deletedIds.add(d.id));
    } catch (e) {
      console.warn("History seed: deleted/exclusion list nahi mil payi:", e);
    }

    const batch = db.batch();
    questions.forEach(([text, options, answer], index) => {
      const id = `history-nationalism-europe-${String(index + 1).padStart(3, "0")}`;
      if (deletedIds.has(id)) return; // pehle delete ho chuka hai, skip
      batch.set(db.collection("questionBank").doc(id), {
        subject: "History",
        chapter: "यूरोप में राष्ट्रवाद",
        text,
        options,
        answer,
        seeded: true,
        updatedAt: firebase.firestore.FieldValue.serverTimestamp(),
        createdAt: firebase.firestore.FieldValue.serverTimestamp(),
      }, { merge: true });
    });
    await batch.commit();
  }


